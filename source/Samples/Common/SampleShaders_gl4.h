const char *SAMPLE_LIT_PIXEL_SHADER_GL =
    "#version 400\n"
    "#extension GL_ARB_separate_shader_objects : require\n"
    "\n"
    "struct PS_INPUT\n"
    "{\n"
    "    vec3 worldNormal;\n"
    "    vec3 worldPos;\n"
    "    vec2 uv;\n"
    "};\n"
    "\n"
    "layout(std140) uniform type_tiny3d_LightParams\n"
    "{\n"
    "    vec4 tiny3d_AmbientLight;\n"
    "    vec4 tiny3d_DirLightColor;\n"
    "    vec4 tiny3d_DirLightDir;\n"
    "    vec4 tiny3d_PointLightColor[4];\n"
    "    vec4 tiny3d_PointLightPos[4];\n"
    "    vec4 tiny3d_PointLightAttenuation[4];\n"
    "    vec4 tiny3d_SpotLightColor[4];\n"
    "    vec4 tiny3d_SpotLightPos[4];\n"
    "    vec4 tiny3d_SpotLightDir[4];\n"
    "    vec4 tiny3d_SpotLightAttenuation[4];\n"
    "} tiny3d_LightParams;\n"
    "\n"
    "layout(std140) uniform type_tiny3d_CameraParams\n"
    "{\n"
    "    vec4 tiny3d_CameraWorldPos;\n"
    "} tiny3d_CameraParams;\n"
    "\n"
    "layout(std140) uniform type_tiny3d_ObjectParams\n"
    "{\n"
    "    vec4 tiny3d_ObjectSmoothness;\n"
    "} tiny3d_ObjectParams;\n"
    "\n"
    "uniform sampler2D SPIRV_Cross_CombinedtexCubesamplertexCube;\n"
    "\n"
    "layout(location = 0) in vec3 in_var_NORMAL;\n"
    "layout(location = 1) in vec3 in_var_COLOR0;\n"
    "layout(location = 2) in vec2 in_var_TEXCOORD0;\n"
    "layout(location = 0) out vec4 out_var_SV_Target;\n"
    "\n"
    "float calculateDiffuse(vec3 normal, vec3 lightDir)\n"
    "{\n"
    "    return max(0.0, dot(normal, lightDir));\n"
    "}\n"
    "\n"
    "float calculateSpecular(vec3 viewDir, vec3 normal, vec3 lightDir, float smoothness)\n"
    "{\n"
    "    float shininess = smoothness * 128.0;\n"
    "    vec3 halfDir = normalize(lightDir + viewDir);\n"
    "    return pow(max(dot(viewDir, halfDir), 0.0), shininess);\n"
    "}\n"
    "\n"
    "vec3 calcDirectionalLight(vec3 normal, vec3 viewDir, vec3 albedo, vec3 lightDir, vec3 lightColor, float diffuseIntensity, float specularIntensity, float smoothness)\n"
    "{\n"
    "    vec3 param_var_normal = normal;\n"
    "    vec3 param_var_lightDir = -lightDir;\n"
    "    float diffuse = calculateDiffuse(param_var_normal, param_var_lightDir);\n"
    "    vec3 param_var_viewDir = viewDir;\n"
    "    vec3 param_var_normal_1 = normal;\n"
    "    vec3 param_var_lightDir_1 = -lightDir;\n"
    "    float param_var_smoothness = smoothness;\n"
    "    float specular = calculateSpecular(param_var_viewDir, param_var_normal_1, param_var_lightDir_1, param_var_smoothness);\n"
    "    return (lightColor * ((diffuse * diffuseIntensity) + (specular * specularIntensity))) * albedo;\n"
    "}\n"
    "\n"
    "float calcLightAttenuation(vec3 lightPos, vec3 pos, float attenuationConstant, float attenuationLinear, float attenuationQuadratic)\n"
    "{\n"
    "    float _distance = length(lightPos - pos);\n"
    "    float denom = (attenuationConstant + (attenuationLinear * _distance)) + ((attenuationQuadratic * _distance) * _distance);\n"
    "    float attenuation = (denom > 0.0) ? (1.0 / denom) : 0.0;\n"
    "    return attenuation;\n"
    "}\n"
    "\n"
    "vec3 calcPointLight(vec3 pos, vec3 normal, vec3 viewDir, vec3 albedo, vec3 lightPos, vec3 lightColor, float diffuseIntensity, float specularIntensity, vec3 attenuation, float smoothness)\n"
    "{\n"
    "    vec3 param_var_lightPos = lightPos;\n"
    "    vec3 param_var_pos = pos;\n"
    "    float param_var_attenuationConstant = attenuation.x;\n"
    "    float param_var_attenuationLinear = attenuation.y;\n"
    "    float param_var_attenuationQuadratic = attenuation.z;\n"
    "    float att = calcLightAttenuation(param_var_lightPos, param_var_pos, param_var_attenuationConstant, param_var_attenuationLinear, param_var_attenuationQuadratic);\n"
    "    vec3 lightDir = normalize(lightPos - pos);\n"
    "    vec3 param_var_normal = normal;\n"
    "    vec3 param_var_lightDir = lightDir;\n"
    "    float diffuse = calculateDiffuse(param_var_normal, param_var_lightDir);\n"
    "    vec3 param_var_viewDir = viewDir;\n"
    "    vec3 param_var_normal_1 = normal;\n"
    "    vec3 param_var_lightDir_1 = lightDir;\n"
    "    float param_var_smoothness = smoothness;\n"
    "    float specular = calculateSpecular(param_var_viewDir, param_var_normal_1, param_var_lightDir_1, param_var_smoothness);\n"
    "    return ((lightColor * ((diffuse * diffuseIntensity) + (specular * specularIntensity))) * albedo) * att;\n"
    "}\n"
    "\n"
    "vec3 calcSpotLight(vec3 pos, vec3 normal, vec3 viewDir, vec3 albedo, vec3 lightPos, vec3 lightDir, vec3 lightColor, float diffuseIntensity, float specularIntensity, vec3 attenuation, float smoothness, float cutoff, float outerCutoff)\n"
    "{\n"
    "    vec3 param_var_lightPos = lightPos;\n"
    "    vec3 param_var_pos = pos;\n"
    "    float param_var_attenuationConstant = attenuation.x;\n"
    "    float param_var_attenuationLinear = attenuation.y;\n"
    "    float param_var_attenuationQuadratic = attenuation.z;\n"
    "    float att = calcLightAttenuation(param_var_lightPos, param_var_pos, param_var_attenuationConstant, param_var_attenuationLinear, param_var_attenuationQuadratic);\n"
    "    vec3 dir = normalize(lightPos - pos);\n"
    "    float theta = dot(dir, -lightDir);\n"
    "    float epsilon = cutoff - outerCutoff;\n"
    "    float intensity = clamp((theta - outerCutoff) / epsilon, 0.0, 1.0);\n"
    "    vec3 param_var_normal = normal;\n"
    "    vec3 param_var_lightDir = dir;\n"
    "    float diffuse = calculateDiffuse(param_var_normal, param_var_lightDir) * intensity;\n"
    "    vec3 param_var_viewDir = viewDir;\n"
    "    vec3 param_var_normal_1 = normal;\n"
    "    vec3 param_var_lightDir_1 = dir;\n"
    "    float param_var_smoothness = smoothness;\n"
    "    float specular = calculateSpecular(param_var_viewDir, param_var_normal_1, param_var_lightDir_1, param_var_smoothness) * intensity;\n"
    "    return ((lightColor * ((diffuse * diffuseIntensity) + (specular * specularIntensity))) * albedo) * att;\n"
    "}\n"
    "\n"
    "vec4 src_frag(PS_INPUT _input)\n"
    "{\n"
    "    float smoothness = tiny3d_ObjectParams.tiny3d_ObjectSmoothness.x;\n"
    "    vec3 ambient = tiny3d_LightParams.tiny3d_AmbientLight.xyz * tiny3d_LightParams.tiny3d_AmbientLight.w;\n"
    "    vec3 viewDir = normalize(tiny3d_CameraParams.tiny3d_CameraWorldPos.xyz - _input.worldPos);\n"
    "    vec3 normal = normalize(_input.worldNormal);\n"
    "    vec4 albedo = texture(SPIRV_Cross_CombinedtexCubesamplertexCube, _input.uv);\n"
    "    vec3 color = vec3(0.0);\n"
    "    float diffuseIntensity = tiny3d_LightParams.tiny3d_DirLightColor.w;\n"
    "    float specularIntensity = tiny3d_LightParams.tiny3d_DirLightDir.w;\n"
    "    vec3 lightDir = tiny3d_LightParams.tiny3d_DirLightDir.xyz;\n"
    "    vec3 lightColor = tiny3d_LightParams.tiny3d_DirLightColor.xyz;\n"
    "    vec3 param_var_normal = normal;\n"
    "    vec3 param_var_viewDir = viewDir;\n"
    "    vec3 param_var_albedo = albedo.xyz;\n"
    "    vec3 param_var_lightDir = lightDir;\n"
    "    vec3 param_var_lightColor = lightColor;\n"
    "    float param_var_diffuseIntensity = diffuseIntensity;\n"
    "    float param_var_specularIntensity = specularIntensity;\n"
    "    float param_var_smoothness = smoothness;\n"
    "    vec3 dirColor = calcDirectionalLight(param_var_normal, param_var_viewDir, param_var_albedo, param_var_lightDir, param_var_lightColor, param_var_diffuseIntensity, param_var_specularIntensity, param_var_smoothness);\n"
    "    color += dirColor;\n"
    "    int i = 0;\n"
    "    i = 0;\n"
    "    for (; i < 4; i++)\n"
    "    {\n"
    "        diffuseIntensity = tiny3d_LightParams.tiny3d_PointLightColor[i].w;\n"
    "        specularIntensity = tiny3d_LightParams.tiny3d_PointLightPos[i].w;\n"
    "        vec3 lightPos = tiny3d_LightParams.tiny3d_PointLightPos[i].xyz;\n"
    "        lightColor = tiny3d_LightParams.tiny3d_PointLightColor[i].xyz;\n"
    "        vec3 param_var_pos = _input.worldPos;\n"
    "        vec3 param_var_normal_1 = normal;\n"
    "        vec3 param_var_viewDir_1 = viewDir;\n"
    "        vec3 param_var_albedo_1 = albedo.xyz;\n"
    "        vec3 param_var_lightPos = lightPos;\n"
    "        vec3 param_var_lightColor_1 = lightColor;\n"
    "        float param_var_diffuseIntensity_1 = diffuseIntensity;\n"
    "        float param_var_specularIntensity_1 = specularIntensity;\n"
    "        vec3 param_var_attenuation = tiny3d_LightParams.tiny3d_PointLightAttenuation[i].xyz;\n"
    "        float param_var_smoothness_1 = smoothness;\n"
    "        vec3 pointColor = calcPointLight(param_var_pos, param_var_normal_1, param_var_viewDir_1, param_var_albedo_1, param_var_lightPos, param_var_lightColor_1, param_var_diffuseIntensity_1, param_var_specularIntensity_1, param_var_attenuation, param_var_smoothness_1);\n"
    "        color += pointColor;\n"
    "        continue;\n"
    "    }\n"
    "    i = 0;\n"
    "    for (; i < 4; i++)\n"
    "    {\n"
    "        diffuseIntensity = tiny3d_LightParams.tiny3d_SpotLightColor[i].w;\n"
    "        specularIntensity = tiny3d_LightParams.tiny3d_SpotLightPos[i].w;\n"
    "        vec3 lightPos_1 = tiny3d_LightParams.tiny3d_SpotLightPos[i].xyz;\n"
    "        vec3 lightDir_1 = tiny3d_LightParams.tiny3d_SpotLightDir[i].xyz;\n"
    "        lightColor = tiny3d_LightParams.tiny3d_SpotLightColor[i].xyz;\n"
    "        float cutoff = tiny3d_LightParams.tiny3d_SpotLightDir[i].w;\n"
    "        float outerCutoff = tiny3d_LightParams.tiny3d_SpotLightAttenuation[i].w;\n"
    "        vec3 param_var_pos_1 = _input.worldPos;\n"
    "        vec3 param_var_normal_2 = normal;\n"
    "        vec3 param_var_viewDir_2 = viewDir;\n"
    "        vec3 param_var_albedo_2 = albedo.xyz;\n"
    "        vec3 param_var_lightPos_1 = lightPos_1;\n"
    "        vec3 param_var_lightDir_1 = lightDir_1;\n"
    "        vec3 param_var_lightColor_2 = lightColor;\n"
    "        float param_var_diffuseIntensity_2 = diffuseIntensity;\n"
    "        float param_var_specularIntensity_2 = specularIntensity;\n"
    "        vec3 param_var_attenuation_1 = tiny3d_LightParams.tiny3d_SpotLightAttenuation[i].xyz;\n"
    "        float param_var_smoothness_2 = smoothness;\n"
    "        float param_var_cutoff = cutoff;\n"
    "        float param_var_outerCutoff = outerCutoff;\n"
    "        vec3 spotColor = calcSpotLight(param_var_pos_1, param_var_normal_2, param_var_viewDir_2, param_var_albedo_2, param_var_lightPos_1, param_var_lightDir_1, param_var_lightColor_2, param_var_diffuseIntensity_2, param_var_specularIntensity_2, param_var_attenuation_1, param_var_smoothness_2, param_var_cutoff, param_var_outerCutoff);\n"
    "        color += spotColor;\n"
    "        continue;\n"
    "    }\n"
    "    vec4 finalColor = vec4((ambient * albedo.xyz) + color, 1.0);\n"
    "    return finalColor;\n"
    "}\n"
    "\n"
    "void main()\n"
    "{\n"
    "    PS_INPUT param_var_input = PS_INPUT(in_var_NORMAL, in_var_COLOR0, in_var_TEXCOORD0);\n"
    "    out_var_SV_Target = src_frag(param_var_input);\n"
    "}\n"
    "\n";

